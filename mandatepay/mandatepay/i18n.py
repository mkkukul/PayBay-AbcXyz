def resolve_lang(argv=None, env=None):
    """Dil seçimi: --lang xx bayrağı, sonra MANDATEPAY_LANG ortam değişkeni, yoksa İngilizce."""
    argv = list(argv or [])
    env = os.environ if env is None else env
    lang = None
    if "--lang" in argv:
        idx = argv.index("--lang")
        if idx + 1 < len(argv):
            lang = argv[idx + 1]
    lang = lang or env.get("MANDATEPAY_LANG") or DEFAULT_LANG
    if lang not in SUPPORTED:
        raise SystemExit(f"Unsupported language '{lang}'. Choose one of: {', '.join(SUPPORTED)}")
    return lang


def t(key, lang=DEFAULT_LANG, **kwargs):
    table = MESSAGES.get(lang, MESSAGES[DEFAULT_LANG])
    text = table.get(key) or MESSAGES[DEFAULT_LANG][key]
    return text.format(**kwargs) if kwargs else text


def placeholders(text):
    return set(re.findall(r"\{(\w+)\}", text))
